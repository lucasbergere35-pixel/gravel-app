export type IconName = keyof typeof ICONS;

export function icon(name: IconName, extraClass = ''): SVGElement {
  const svg = createElement(ICONS[name], { class: `ico ${extraClass}`.trim(), 'aria-hidden': 'true', 'stroke-width': 2.2 });
  return svg;
}
